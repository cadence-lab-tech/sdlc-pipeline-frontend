#!/usr/bin/env bash
# Сквозные проверки интерфейса поверх живого бэкенда.
#
# Порядок сценариев значим: workflow.mjs активирует новую версию цикла, после
# чего прежние сценарии шли бы уже по другому циклу. База поднимается заново,
# потому что сиды не идемпотентны.
set -euo pipefail

API=${SDLC_API_URL:-http://localhost:8088}
UI=${SDLC_UI_URL:-http://localhost:5173}
PORT=${SDLC_CDP_PORT:-9333}
CHROME=${CHROME:-"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"}
PROFILE=$(mktemp -d)

"$CHROME" --headless --disable-gpu --remote-debugging-port="$PORT" \
  --user-data-dir="$PROFILE" about:blank >/dev/null 2>&1 &
CHROME_PID=$!
trap 'kill $CHROME_PID 2>/dev/null || true; wait $CHROME_PID 2>/dev/null || true; rm -rf "$PROFILE"' EXIT

for _ in $(seq 1 30); do
  curl -sf "http://127.0.0.1:$PORT/json/version" >/dev/null && break
  sleep 1
done

# Словари подписей проверяются без браузера и живого бэкенда — они ни от чего
# не зависят, поэтому идут первыми и падают раньше долгих сценариев.
node e2e/labels.mjs
# Правила строки задачи «Обзора» (CLAB-364): поля списка и их умолчания,
# словарь причин, порядок, ожидание решения, прежняя версия, прогресс эпика,
# стоимость одной цифрой, чужой цикл, ключи и сырые цвета в коде строки —
# тоже без браузера.
node e2e/task-row-rules.mjs
# Правила страницы «Бэклог» (CLAB-402): запросы, края меню порядка и тела
# запросов, перенос, тексты ошибок и объявлений, право уровня agent, ключ
# раскрытия эпика, отложенное перечитывание, подпись task.ranked, ключи и
# сырые цвета в коде страницы — тоже без браузера.
node e2e/backlog-rules.mjs
# Правила «Обзора» (CLAB-365): запросы зон, инвариант «одна задача — одна
# зона», склейка /approvals со строками, дорожки, очередь, адрес фильтров,
# порог панели, состояния и ключи в коде страницы — тоже без браузера.
node e2e/overview-rules.mjs
# Живое обновление «Обзора» (CLAB-367): паузы, коды ответов, схлопывание
# пачки, рукопожатие, скрытая вкладка, запасной режим, смена проекта,
# индикатор и литералы типов событий в коде — тоже без браузера.
node e2e/overview-live-rules.mjs
# Фокус «Обзора» при автообновлении (CLAB-367, AC-14.13): куда возвращается
# фокус строки, переехавшей между зонами, и неблокируемые кнопки — тоже без
# браузера.
node e2e/overview-focus-rules.mjs
# Раскладка схемы цикла и правила состояния на ней (CLAB-284) — тоже без
# браузера: записанные циклы, синтетические графы и все версии циклов стенда.
node e2e/cycle-layout.mjs
# Раскладка «Пайплайна» по слоям и правила адреса страницы (CLAB-346) — тоже
# без браузера: синтетика, наши циклы и все версии циклов стенда.
node e2e/pipeline-layout.mjs
# Правила панели выбранного этапа (CLAB-285): попытки, возвраты, стоимость,
# этап без прогонов и поиск ключей статусов и ролей в модулях карточки — тоже
# без браузера.
node e2e/stage-panel.mjs
# Правила документов версии роли (CLAB-347): нормализация, дифф по документам,
# черновик формы «Новая версия», разбор отказа — тоже без браузера.
node e2e/role-docs.mjs
# Правила отбора документов роли на статусе (CLAB-348): что получит этап,
# подписи панели статуса, состояние поля в диалоге — тоже без браузера.
node e2e/status-docs.mjs
# Правила библиотеки инструкций (CLAB-351): отметки «Обновить в ролях»,
# подписи, закрепление в черновике версии роли, метки привязки в диффе —
# тоже без браузера.
node e2e/library-rules.mjs
# Правила предложений версий роли (CLAB-384): права (кто предлагает, решает и
# отзывает), шапка роли, словарь состояний, номера #k, очередь, «Прочее» против
# последней версии, ключи и сырые цвета в модулях — тоже без браузера.
node e2e/proposal-rules.mjs
# Право этапа (CLAB-383, решение 0072): кнопки карточки и «Ждут меня» по
# полям ответа сервера, текст отказа, пометка самоапрува в ленте, сервер
# прежней версии, сопровождающий, ключи ролей в коде — тоже без браузера.
node e2e/stage-rights-rules.mjs
# Правила стоимости на экранах (CLAB-223): формат денег, подписи двух видов
# стоимости, состояний учёта и типа оплаты — тоже без браузера.
node e2e/cost-rules.mjs
# Правила блока «Что держит» в обзоре задачи (CLAB-286): держащие гейты,
# исполнитель и аренда, перепроверка — тоже без браузера.
node e2e/holding.mjs
# Правила вложений (CLAB-299): тип → режим превью, имя, предел, порядок частей
# формы, виды контракта — тоже без браузера.
node e2e/attachments-rules.mjs
# Правила плиток файлов (CLAB-308): цепочка версий, плитка артефакта и вложения,
# право «Принять», сырые цвета — тоже без браузера.
node e2e/file-tile-rules.mjs
# Страница входа ничего не меняет в данных и идёт первой: она вне оболочки, и
# порядок с остальными сценариями не связан.
node e2e/login.mjs
# Сведения об инстансе: версия в подвале, команды CLI на входе, один запрос
# /v1/instance. Данных не меняет; профиль стенда ему не важен. Сценарий
# профиля single (e2e/single.mjs) сюда не входит: ему нужен свой стенд.
node e2e/instance.mjs
# Страница подключения /docs (CLAB-232): данных не меняет, набор агента
# берёт с /v1/agent-kit стенда; сервер без набора и пользователь без
# проектов подменяются в браузере.
node e2e/docs.mjs
# Проекты и «Обзор»: заводит свою задачу и начинает её, демонстрационных
# задач не двигает.
node e2e/overview.mjs
# Блок «Приоритетные из бэклога» на «Обзоре» (CLAB-366): заводит свои задачи
# и эпики; порядок и total — от сервера, переключатель 5 | 10, нарезка эпика,
# пустые состояния, 400 на order, ошибка блока.
node e2e/overview-backlog.mjs
# Живое обновление «Обзора» (CLAB-367): задача переходит командой API при
# открытой странице — строка меняется без «Обновить» не позже чем через 5 с;
# тихий проект, 404 ручки, скрытая вкладка, «Нет связи», наблюдатель, смена
# проекта. Заводит свои задачи и проекты.
node e2e/overview-live.mjs
# Страница «Бэклог» (CLAB-402): свой проект с импортированной связкой (цикл
# todo/doing/finished, типы task и bug), меню порядка, приоритет в строке,
# эпик в работе с раскрытием, живое обновление, отказы и наблюдатель
# подменой одной ручки, состояния, 390 px и тёмная тема. Проект удаляется.
node e2e/backlog.mjs
# Задача должна стоять на статусе с гейтами, иначе сценарий карточки бессмыслен.
curl -s -X POST "$API/v1/tasks/SDLC-1/transitions/start" \
  -H 'Content-Type: application/json' -H 'X-SDLC-Actor: e2e' -d '{}' >/dev/null
node e2e/task.mjs
# Аренду берёт настоящий агент: экран показывает то, что лежит на прогоне
# аналитики SDLC-1, и подделывать это в браузере нечем.
curl -s -X POST "$API/v1/tasks/SDLC-1/claim" \
  -H 'Content-Type: application/json' -H 'X-SDLC-Actor: agent:analyst-bot' \
  -d '{"role":"analyst"}' >/dev/null
node e2e/knowledge.mjs
node e2e/epic.mjs
# Роли на странице «Пайплайн» (CLAB-346, CLAB-347): панель роли, документы и
# дифф версий на своей роли, новая версия документами, отказы, архив,
# «Завести роль» в своём пустом проекте.
node e2e/roles.mjs
# Предложения версий роли (CLAB-384): agent предлагает и отзывает, сопровождающий
# утверждает, отклоняет с заметкой и видит «устарело», гонка 409 stale_role_base,
# наблюдатель, «Новая версия» без изменений, сбои, 390 px и тёмная тема. Своя роль
# `e2e-prop-*`; кто я подменяется в браузере, запросы идут от настоящих акторов.
node e2e/role-proposals.mjs
# Страница «Пайплайн»: адрес, старые адреса, узлы с версиями ролей,
# состояния, узкий и широкий экран. Данных не меняет.
node e2e/pipeline.mjs
# Отбор документов роли на статусе (CLAB-348): поле в диалоге статуса,
# счётчик и строка отбора в панели, сбой и загрузка версии роли, активная
# версия. Заводит свой проект импортом связки, демонстрационный не трогает.
node e2e/status-docs-screen.mjs
# Библиотека инструкций (CLAB-351): «В библиотеку», «Обновить в ролях» с
# гонкой 409, панель инструкции, «Новая версия», «есть новее», форма версии
# роли с «Из библиотеки» и «Отвязать», наблюдатель и сервер без библиотеки.
# Свои роли и инструкция с отметкой прогона: повторяется на той же базе.
node e2e/library.mjs
node e2e/settings.mjs
# Состояние приложения GitHub и отметки в меню сверяются с тем, что отдаёт
# бэкенд этого стенда: сценарий ничего не предполагает о том, читаются ли
# репозитории демонстрационного проекта. Идёт после настроек — к этому
# моменту воркер успел пройти по репозиториям дважды, если он включён.
node e2e/health.mjs
# Журнал действий и подробности ленты (CLAB-211): сценарий заводит себе свою
# задачу и делает с ней всё ручками API, демонстрационные не трогает. Идёт до
# правки цикла: его переходы — переходы демонстрационного цикла.
node e2e/audit.mjs
# Уровень модели (CLAB-262): заводит свою задачу и свои роли, демонстрационных
# не трогает. Идёт до правки цикла: захват и переход — по демонстрационному.
node e2e/model-level.mjs
# Право этапа в браузере (CLAB-383): кнопки апрува и перехода своего и чужого
# этапа, текст отказа сервера, ни одного POST при открытой карточке, пометка
# самоапрува в настоящей ленте, «Ждут меня» с can_decide: false. Заводит свои
# задачи и участника-аналитика, демонстрационных не трогает. Идёт до правки
# цикла: гейты и переходы — демонстрационного.
node e2e/stage-rights.mjs
# Вложения в карточке (CLAB-299): заводит свои задачи (обычную, эпик и по
# отменённой каждого типа), прикрепляет, версионирует, смотрит и скачивает
# настоящие файлы, демонстрационных SDLC-1 и SDLC-2 не трогает. Идёт до правки
# цикла: старт и захват своей задачи — по демонстрационному.
node e2e/attachments.mjs
# Экраны стоимости (CLAB-223): заводит свою команду, проект с переносом связки,
# эпик с задачами и отчёты агентов; демонстрационных данных не трогает. Идёт до
# правки цикла: переходы — по циклу, перенесённому из демонстрационного.
node e2e/cost.mjs
# Схема цикла в карточке (CLAB-284): заводит свою задачу и двигает её ручками
# API, демонстрационных не трогает. Идёт до правки цикла: переходы — по
# демонстрационному.
node e2e/cycle.mjs
# Необязательные этапы (CLAB-318): форма новой задачи, блок «Выбор этапов» в карточке,
# «пропущен» и «выключен» на схеме, переход с пропуском, недоступный возврат.
# Заводит свой проект и цикл через импорт связки, демонстрационный SDLC не
# трогает; идёт до правки цикла по порядку, но от неё не зависит.
node e2e/optional-stages.mjs
# Команды заводятся до правки цикла: сценарий цикла активирует новую версию,
# после чего прежние экраны идут уже по другому циклу.
# Участник e2e-lead должен существовать до добавления в состав: человек по
# хэндлу не заводится (решение 0033), а актор заголовка — заводится.
curl -s "$API/v1/projects" -H 'X-SDLC-Actor: e2e-lead' >/dev/null
node e2e/admin.mjs
node e2e/workflow.mjs
# Схема после активации новой версии (CLAB-284): начатая задача — на прежней,
# задача из бэклога — на новой. Поэтому сразу после workflow.mjs.
node e2e/cycle-version.mjs
# Приглашения — последними: приём добавляет участников в SDLC, и прежним
# сценариям их видеть незачем. Второй человек — актор заголовка.
node e2e/invite.mjs
