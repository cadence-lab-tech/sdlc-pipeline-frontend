#!/usr/bin/env bash
# Сквозные проверки интерфейса поверх живого бэкенда.
#
# Порядок сценариев значим: workflow.mjs активирует новую версию цикла, после
# чего прежние сценарии шли бы уже по другому циклу. База поднимается заново,
# потому что сиды не идемпотентны.
set -euo pipefail

API=${SDLC_API_URL:-http://localhost:8088}
UI=${SDLC_UI_URL:-http://localhost:5173}
PORT=${SDLC_CDP_PORT:-9333}
CHROME=${CHROME:-"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"}
PROFILE=$(mktemp -d)

"$CHROME" --headless --disable-gpu --remote-debugging-port="$PORT" \
  --user-data-dir="$PROFILE" about:blank >/dev/null 2>&1 &
CHROME_PID=$!
trap 'kill $CHROME_PID 2>/dev/null || true; wait $CHROME_PID 2>/dev/null || true; rm -rf "$PROFILE"' EXIT

for _ in $(seq 1 30); do
  curl -sf "http://127.0.0.1:$PORT/json/version" >/dev/null && break
  sleep 1
done

# Словари подписей проверяются без браузера и живого бэкенда — они ни от чего
# не зависят, поэтому идут первыми и падают раньше долгих сценариев.
node e2e/labels.mjs
# Раскладка схемы цикла и правила состояния на ней (CLAB-284) — тоже без
# браузера: записанные циклы, синтетические графы и все версии циклов стенда.
node e2e/cycle-layout.mjs
# Правила панели выбранного этапа (CLAB-285): попытки, возвраты, стоимость,
# этап без прогонов и поиск ключей статусов и ролей в модулях карточки — тоже
# без браузера.
node e2e/stage-panel.mjs
# Правила стоимости на экранах (CLAB-223): формат денег, подписи двух видов
# стоимости, состояний учёта и типа оплаты — тоже без браузера.
node e2e/cost-rules.mjs
# Правила блока «Что держит» в обзоре задачи (CLAB-286): держащие гейты,
# исполнитель и аренда, перепроверка — тоже без браузера.
node e2e/holding.mjs
# Страница входа ничего не меняет в данных и идёт первой: она вне оболочки, и
# порядок с остальными сценариями не связан.
node e2e/login.mjs
# Сведения об инстансе: версия в подвале, команды CLI на входе, один запрос
# /v1/instance. Данных не меняет; профиль стенда ему не важен. Сценарий
# профиля single (e2e/single.mjs) сюда не входит: ему нужен свой стенд.
node e2e/instance.mjs
# Страница подключения /docs (CLAB-232): данных не меняет, набор агента
# берёт с /v1/agent-kit стенда; сервер без набора и пользователь без
# проектов подменяются в браузере.
node e2e/docs.mjs
node e2e/board.mjs
# Задача должна стоять на статусе с гейтами, иначе сценарий карточки бессмыслен.
curl -s -X POST "$API/v1/tasks/SDLC-1/transitions/start" \
  -H 'Content-Type: application/json' -H 'X-SDLC-Actor: e2e' -d '{}' >/dev/null
node e2e/task.mjs
# Аренду берёт настоящий агент: экран показывает то, что лежит на прогоне
# аналитики SDLC-1, и подделывать это в браузере нечем.
curl -s -X POST "$API/v1/tasks/SDLC-1/claim" \
  -H 'Content-Type: application/json' -H 'X-SDLC-Actor: agent:analyst-bot' \
  -d '{"role":"analyst"}' >/dev/null
node e2e/knowledge.mjs
node e2e/epic.mjs
node e2e/roles.mjs
node e2e/settings.mjs
# Состояние приложения GitHub и отметки в меню сверяются с тем, что отдаёт
# бэкенд этого стенда: сценарий ничего не предполагает о том, читаются ли
# репозитории демонстрационного проекта. Идёт после настроек — к этому
# моменту воркер успел пройти по репозиториям дважды, если он включён.
node e2e/health.mjs
# Журнал действий и подробности ленты (CLAB-211): сценарий заводит себе свою
# задачу и делает с ней всё ручками API, демонстрационные не трогает. Идёт до
# правки цикла: его переходы — переходы демонстрационного цикла.
node e2e/audit.mjs
# Уровень модели (CLAB-262): заводит свою задачу и свои роли, демонстрационных
# не трогает. Идёт до правки цикла: захват и переход — по демонстрационному.
node e2e/model-level.mjs
# Экраны стоимости (CLAB-223): заводит свою команду, проект с переносом связки,
# эпик с задачами и отчёты агентов; демонстрационных данных не трогает. Идёт до
# правки цикла: переходы — по циклу, перенесённому из демонстрационного.
node e2e/cost.mjs
# Схема цикла в карточке (CLAB-284): заводит свою задачу и двигает её ручками
# API, демонстрационных не трогает. Идёт до правки цикла: переходы — по
# демонстрационному.
node e2e/cycle.mjs
# Команды заводятся до правки цикла: сценарий цикла активирует новую версию,
# после чего прежние экраны идут уже по другому циклу.
# Участник e2e-lead должен существовать до добавления в состав: человек по
# хэндлу не заводится (решение 0033), а актор заголовка — заводится.
curl -s "$API/v1/projects" -H 'X-SDLC-Actor: e2e-lead' >/dev/null
node e2e/admin.mjs
node e2e/workflow.mjs
# Схема после активации новой версии (CLAB-284): начатая задача — на прежней,
# задача из бэклога — на новой. Поэтому сразу после workflow.mjs.
node e2e/cycle-version.mjs
# Приглашения — последними: приём добавляет участников в SDLC, и прежним
# сценариям их видеть незачем. Второй человек — актор заголовка.
node e2e/invite.mjs
