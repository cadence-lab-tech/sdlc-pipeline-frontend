// Цена удаления словами. Счётчики (`removed`) бэкенд считает до удаления и
// отдаёт только в ответе: ручки-предпросмотра нет, поэтому диалог называет
// категории того, что исчезнет, а числа показываются после действия — в тосте.
//
// Нули не перечисляются: «файлов 0» ничего не сообщает, а длинный список из
// них прячет то, что действительно ушло. Не ушло ничего — так и сказано, а не
// пустой строкой.
export function counted(pairs: [string, number][]): string {
  const said = pairs.filter(([, n]) => n > 0).map(([label, n]) => `${label} ${n}`);
  return said.length > 0 ? said.join(', ') : 'связанных данных не было';
}
