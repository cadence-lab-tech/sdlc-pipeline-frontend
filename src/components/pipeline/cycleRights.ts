// Правка цикла на «Пайплайне» (CLAB-409, R-16): кнопки черновика неактивны,
// когда интерфейс знает, что права нет, и рядом стоит пояснение. Право — только
// подсказка: сервер проверяет всё равно, и отказ придёт 403. «Не знаю» (кто я
// не загрузился, режим header, администратор системы) — это «можно».
// Предложение версии роли и библиотеку инструкций это правило не касается.
//
// Модуль без разметки и без путей '@/': e2e/task-rights-rules.mjs проверяет
// его node без сборщика.
export const CYCLE_READONLY_HINT = 'цикл правит сопровождающий проекта';

export interface CycleControls {
  // Правится ли черновик на холсте и в панелях: черновик и право.
  editable: boolean;
  // Кнопки правки цикла (создать черновик, название и типы, удалить,
  // активировать, добавить статус) неактивны.
  locked: boolean;
  // Пояснение рядом с кнопками; нет, когда право есть.
  hint?: string;
}

// mayEdit — подсказка интерфейса: false, только если право известно и его нет.
export function cycleControls(isDraft: boolean, mayEdit: boolean): CycleControls {
  return {editable: isDraft && mayEdit, locked: !mayEdit, hint: mayEdit ? undefined : CYCLE_READONLY_HINT};
}
